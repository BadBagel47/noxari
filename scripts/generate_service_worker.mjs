// F-028: write dist/sw.js with a precache list of the built app (paths relative to the
// service worker's scope, so the same file works at /noxari/ and at the domain root).
import {createHash} from 'node:crypto';
import {readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs';
import {join, relative} from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;
const skip = [/^sky\/milky-way-color-v1\.webp$/, /^share\//, /^stars\//, /^images\/objects\//, /^labs\//, /^sw\.js$/, /\.map$/, /^data\//];
const files = [];
const walk = dir => { for (const name of readdirSync(dir)) { const path = join(dir, name); if (statSync(path).isDirectory()) walk(path); else files.push(relative(dist, path).split('\\').join('/')); } };
walk(dist);
const precache = files.filter(file => !skip.some(rule => rule.test(file))).sort();
const version = createHash('sha256').update(precache.map(file => file + readFileSync(join(dist, file)).length).join('|')).digest('hex').slice(0, 12);
const sw = `// Generated by scripts/generate_service_worker.mjs — Noxari offline cache (F-028).
const CACHE = 'noxari-${version}';
const PRECACHE = ${JSON.stringify(['./', ...precache.filter(file => file !== 'index.html')])};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith('noxari-') && key !== CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return; // weather, satellite data etc. go straight to the network
  if (request.mode === 'navigate' || url.pathname.includes('/data/')) {
    // Network first for the page and refreshed data (ISS elements); cached copies work offline.
    const key = request.mode === 'navigate' ? './' : request;
    event.respondWith(fetch(request).then(response => { if (response.ok) { const copy = response.clone(); caches.open(CACHE).then(cache => cache.put(key, copy)); } return response; })
      .catch(() => caches.match(key).then(hit => hit || caches.match('./'))));
    return;
  }
  event.respondWith(caches.match(request).then(hit => hit || fetch(request).then(response => {
    if (response.ok) { const copy = response.clone(); caches.open(CACHE).then(cache => cache.put(request, copy)); }
    return response;
  })));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`Service worker: ${precache.length} files, cache noxari-${version}`);
