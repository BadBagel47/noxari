"""Generate Noxari's bright-star subset from HYG v4.1 (CC BY-SA 4.0)."""

import csv
import hashlib
import io
import json
from pathlib import Path
from urllib.request import urlopen
import sys

SOURCE = 'https://raw.githubusercontent.com/astronexus/HYG-Database/main/hyg/CURRENT/hygdata_v41.csv'
SHA256 = 'd9f69fd86bbf90a4e4d52b4c5c53eacfa6dfc0bfdef85bfd94f095e0bebe4ebd'
OUTPUT = Path(__file__).resolve().parents[1] / 'src/generated/brightStars.ts'


def main() -> None:
    if len(sys.argv) > 1:
        raw = Path(sys.argv[1]).read_bytes()
    else:
        with urlopen(SOURCE, timeout=60) as response:
            raw = response.read()
    actual = hashlib.sha256(raw).hexdigest()
    if actual != SHA256:
        raise SystemExit(f'HYG source checksum mismatch: {actual}')

    stars = []
    for row in csv.DictReader(io.StringIO(raw.decode('utf-8-sig'))):
        if row['id'] == '0' or not all(row[field] for field in ('ra', 'dec', 'mag')):
            continue  # HYG row zero is the Sun, not a fixed star.
        magnitude = float(row['mag'])
        if magnitude > 5.8:
            continue
        entry = [round(float(row['ra']), 6), round(float(row['dec']), 6), round(magnitude, 2)]
        if row['proper'] and magnitude <= 0.5:
            entry.append(row['proper'])
        stars.append(entry)
    if len(stars) != 4105:
        raise SystemExit(f'Unexpected bright-star count: {len(stars)}')
    header = (
        '// Generated by scripts/generate_bright_stars.py from HYG v4.1.\n'
        '// Source: https://github.com/astronexus/HYG-Database\n'
        '// HYG Database by Astronexus contributors. CC BY-SA 4.0.\n'
        '// This adapted subset (magnitude <= 5.8, excluding Sol) is shared under CC BY-SA 4.0.\n'
        'export type BrightStar = [raHours: number, decDegrees: number, magnitude: number, name?: string];\n'
    )
    OUTPUT.write_text(header + 'export const brightStars: BrightStar[] = ' + json.dumps(stars, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'Wrote {len(stars)} stars to {OUTPUT}')


if __name__ == '__main__':
    main()
