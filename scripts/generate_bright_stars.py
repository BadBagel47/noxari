"""Generate stars with proper motion and 88 constellation figures (CC BY-SA 4.0)."""
import csv
import hashlib
import io
import json
from pathlib import Path
from urllib.request import urlopen
import sys

SOURCE = 'https://raw.githubusercontent.com/astronexus/HYG-Database/main/hyg/CURRENT/hygdata_v41.csv'
SHA256 = 'd9f69fd86bbf90a4e4d52b4c5c53eacfa6dfc0bfdef85bfd94f095e0bebe4ebd'
STELLARIUM_COMMIT = 'daace2add6a1bf886e8ee1934f51e9c69f818d18'
FIGURES_SOURCE = f'https://raw.githubusercontent.com/Stellarium/stellarium/{STELLARIUM_COMMIT}/skycultures/modern/index.json'
FIGURES_SHA256 = '1f2f5ffd6c9e25a7d0dcfdbf1f756e2db03dd3b8ed4ec016a2839b09f6b0fe1e'
OUTPUT = Path(__file__).resolve().parents[1] / 'src/generated'


def source(url, checksum, local=None):
    raw = Path(local).read_bytes() if local else urlopen(url, timeout=60).read()
    actual = hashlib.sha256(raw).hexdigest()
    if actual != checksum:
        raise SystemExit(f'Source checksum mismatch for {url}: {actual}')
    return raw


def main():
    raw = source(SOURCE, SHA256, sys.argv[1] if len(sys.argv) > 1 else None)
    figures_raw = source(FIGURES_SOURCE, FIGURES_SHA256, sys.argv[2] if len(sys.argv) > 2 else None)
    figures = json.loads(figures_raw)['constellations']
    required = {hip for figure in figures for line in figure['lines'] for hip in line}
    stars, available = [], set()
    for row in csv.DictReader(io.StringIO(raw.decode('utf-8-sig'))):
        if row['id'] == '0' or not all(row[field] for field in ('ra', 'dec', 'mag')):
            continue
        hip = int(row['hip']) if row['hip'] else None
        magnitude = float(row['mag'])
        if magnitude > 5.8 and hip not in required:
            continue
        stars.append([round(float(row['ra']), 6), round(float(row['dec']), 6), round(magnitude, 2),
                      row['proper'] if row['proper'] and magnitude <= .5 else None,
                      float(row['pmra'] or 0), float(row['pmdec'] or 0), hip])
        available.add(hip)
    if len(stars) != 4110 or required - available:
        raise SystemExit(f'Invalid subset: {len(stars)} stars, missing HIP {required - available}')
    header = (
        '// Generated by scripts/generate_bright_stars.py from HYG v4.1.\n'
        '// Source: https://github.com/astronexus/HYG-Database\n'
        '// Astronexus contributors. Adapted subset: CC BY-SA 4.0.\n'
        '// 4105 stars to magnitude 5.8 plus 5 fainter constellation endpoints.\n'
        '// J2000 coordinates; pmRaCosDec and pmDec in milliarcseconds/year.\n'
        'export type BrightStar = [raHours: number, decDegrees: number, magnitude: number, name: string | null, pmRaCosDec: number, pmDec: number, hip: number | null];\n'
    )
    (OUTPUT / 'brightStars.ts').write_text(header + 'export const brightStars: BrightStar[] = ' + json.dumps(stars, ensure_ascii=False, separators=(',', ':')) + ';\n')
    adapted = [dict(id=c['id'].split()[-1], name=c['common_name']['native'], lines=c['lines']) for c in figures]
    assert len(adapted) == 88 and all(c['lines'] for c in adapted)
    header = (
        '// Adapted from Stellarium modern skyculture (Stellarium team), CC BY-SA 4.0.\n'
        f'// Source: {FIGURES_SOURCE}\n'
        '// Only Latin names and HIP line connectivity; no artwork or official boundaries.\n'
        'export type ConstellationFigure = {id: string; name: string; lines: number[][]};\n'
    )
    (OUTPUT / 'constellations.ts').write_text(header + 'export const constellationFigures: ConstellationFigure[] = ' + json.dumps(adapted, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'Wrote {len(stars)} stars and {len(adapted)} constellation figures')


if __name__ == '__main__':
    main()
