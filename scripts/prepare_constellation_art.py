"""F-041: download Stellarium 'modern' sky-culture illustrations (Free Art License)
at a pinned commit, tint them for Noxari (style B) and write anchors.

Source: https://github.com/Stellarium/stellarium/tree/<PIN>/skycultures/modern
License: illustrations Free Art License (https://artlibre.org/licence/lal/en/),
per skycultures/modern/description.md at the pinned commit. Tinted output is a
modified work and is distributed under the same license.

Run: python3 scripts/prepare_constellation_art.py
Writes: public/constellation-art/<id>.webp, src/generated/constellationArt.ts,
data/stellarium-art/manifest.json (SHA-256 of originals)."""
import hashlib, io, json, urllib.request
from pathlib import Path
from PIL import Image

PIN = 'daace2add6a1bf886e8ee1934f51e9c69f818d18'
BASE = f'https://raw.githubusercontent.com/Stellarium/stellarium/{PIN}/skycultures/modern'
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'public' / 'constellation-art'
SIZE = 384
TINT = (134, 203, 239)
HYG = 'https://raw.githubusercontent.com/astronexus/HYG-Database/3bf37f4b2d5460e1278286320d1d62fab9b493c1/hyg/CURRENT/hygdata_v41.csv'

def anchor_coordinates(hips):
    """J2000 RA (hours) / Dec (degrees) for anchor stars from the pinned HYG v4.1 catalog (CC BY-SA 4.0)."""
    import csv
    with urllib.request.urlopen(HYG, timeout=300) as response:
        rows = csv.DictReader(io.TextIOWrapper(response, encoding='utf-8'))
        found = {}
        for row in rows:
            if row['hip'] and int(row['hip']) in hips:
                found[int(row['hip'])] = (round(float(row['ra']), 6), round(float(row['dec']), 6))
    missing = hips - set(found)
    if missing: raise SystemExit(f'anchor stars missing from HYG: {sorted(missing)}')
    return found

def fetch(path):
    with urllib.request.urlopen(f'{BASE}/{path}', timeout=60) as response:
        return response.read()

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    index = json.loads(fetch('index.json'))
    entries, manifest = [], {}
    for con in index['constellations']:
        image = con.get('image')
        if not image:
            continue
        cid = con['id'].split()[-1]
        raw = fetch(image['file'])
        manifest[cid] = {'file': image['file'], 'sha256': hashlib.sha256(raw).hexdigest()}
        gray = Image.open(io.BytesIO(raw)).convert('L')
        scale = SIZE / gray.width
        gray = gray.resize((SIZE, round(gray.height * scale)), Image.LANCZOS)
        alpha = gray.point(lambda v: round(v * 0.85))
        rgba = Image.new('RGBA', gray.size, TINT + (0,))
        rgba.putalpha(alpha)
        rgba.save(OUT / f'{cid}.webp', 'WEBP', quality=82, method=6)
        entries.append({'id': cid, 'w': gray.width, 'h': gray.height,
                        'anchors': [[round(a['pos'][0] * scale, 2), round(a['pos'][1] * scale, 2), a['hip']] for a in image['anchors']]})
    coords = anchor_coordinates({a[2] for e in entries for a in e['anchors']})
    for e in entries:
        e['anchors'] = [[u, v, hip, *coords[hip]] for u, v, hip in e['anchors']]
    (ROOT / 'data' / 'stellarium-art' / 'manifest.json').write_text(json.dumps({'pin': PIN, 'source': BASE, 'license': 'Free Art License 1.3', 'licenseUrl': 'https://artlibre.org/licence/lal/en/', 'images': manifest}, indent=1) + '\n')
    ts = ('// Generated by scripts/prepare_constellation_art.py — do not edit.\n'
          f'// Illustrations: Stellarium team, modern sky culture @ {PIN}, Free Art License 1.3\n'
          '// (https://artlibre.org/licence/lal/en/). Tinted by Noxari; same license applies.\n'
          '// anchors: [imageX, imageY, hip, raHours J2000, decDegrees J2000] from HYG v4.1 (CC BY-SA 4.0).\n'
          'export type ConstellationArt = {id: string; w: number; h: number; anchors: [number, number, number, number, number][]};\n'
          f'export const constellationArt: ConstellationArt[] = {json.dumps(entries, separators=(",", ":"))};\n')
    (ROOT / 'src' / 'generated' / 'constellationArt.ts').write_text(ts)
    print(len(entries), 'illustrations')

if __name__ == '__main__':
    main()
