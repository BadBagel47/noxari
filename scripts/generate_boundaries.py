"""Extract official IAU boundaries from pinned Stellarium modern skyculture.

Usage: python3 scripts/generate_boundaries.py [index.json description.md]
Python standard library only. Adaptation licensed CC BY-SA 4.0.
"""
import hashlib
import json
import sys
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
COMMIT = 'daace2add6a1bf886e8ee1934f51e9c69f818d18'
BASE = f'https://raw.githubusercontent.com/Stellarium/stellarium/{COMMIT}/skycultures/modern/'
INPUTS = [('index.json', '1f2f5ffd6c9e25a7d0dcfdbf1f756e2db03dd3b8ed4ec016a2839b09f6b0fe1e'),
          ('description.md', '4b58344f63168d7c816fdfef405103b5770fda2e1f4a4bf5c8871041ce042586')]


def sexagesimal(value):
    h, m, s = map(int, value.lstrip('+-').split(':'))
    return round((-1 if value.startswith('-') else 1) * (h + m / 60 + s / 3600), 10)


def main():
    sources = []
    for i, (name, checksum) in enumerate(INPUTS, 1):
        raw = Path(sys.argv[i]).read_bytes() if len(sys.argv) > i else urlopen(BASE + name, timeout=60).read()
        if hashlib.sha256(raw).hexdigest() != checksum:
            raise SystemExit(f'{name}: checksum mismatch; review upstream before changing pins')
        sources.append(raw.decode())
    data = json.loads(sources[0])
    assert 'Text and data: CC BY-SA 4.0' in sources[1]
    assert data['edges_type'] == 'iau' and data['edges_epoch'] == 'B1875'
    assert data['edges_source'] == 'https://pbarbier.com/constellations/edges_18.txt'
    ids = {c['id'].split()[-1].upper(): c['id'].split()[-1] for c in data['constellations']}
    ids.update(SER1='Ser1', SER2='Ser2')
    edges = []
    for line in data['edges']:
        _, direction, ra1, dec1, ra2, dec2, left, right = line.split()
        a, b, c, d = map(sexagesimal, (ra1, dec1, ra2, dec2))
        assert 0 <= a < 24 and 0 <= c < 24 and -90 <= b <= 90 and -90 <= d <= 90
        assert direction in ('M+', 'P+') and left != right
        if direction == 'M+':
            assert a == c and b < d
        else:
            assert b == d and a != c
            if c < a:
                c += 24  # P+ means increasing RA, including the 24h seam.
        edges.append([a, b, c, d, ids[left], ids[right]])
    assert len(edges) == 781 and len({tuple(e[:4]) for e in edges}) == 781
    assert len({r.removesuffix('1').removesuffix('2') for e in edges for r in e[4:]}) == 88
    header = ('// Generated by scripts/generate_boundaries.py; adapted Stellarium team data, CC BY-SA 4.0.\n'
              f'// Pinned commit {COMMIT}; IAU edges via Pierre Barbier, B1875.\n'
              '// P+ seam crossings use end RA > 24h; Ser1/Ser2 are the two regions of Serpens.\n'
              'export type BoundaryEdge = readonly [raStart: number, decStart: number, raEnd: number, decEnd: number, left: string, right: string];\n')
    (ROOT / 'src/generated/boundaries.ts').write_text(header + 'export const constellationBoundaries: readonly BoundaryEdge[] = ' + json.dumps(edges, separators=(',', ':')) + ';\n')
    print(f'Wrote {len(edges)} unique B1875 edges for all 88 constellations (89 regions).')


if __name__ == '__main__':
    main()
