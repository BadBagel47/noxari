"""F-045: apparent sizes for the 110 Messier objects (OpenNGC, CC BY-SA 4.0).

Same pinned OpenNGC commit, files and checksums as scripts/generate_messier.py,
and the same identity mapping (M102 = NGC 5866, following NASA/Hubble). Only the
MajAx/MinAx columns (arcminutes) are taken; Messier records in
src/generated/messier.ts are not changed. Distances for the approximate true size
come from the existing NASA/Hubble snapshot (data/messier-distances.json).

Run: python3 scripts/generate_messier_sizes.py [NGC.csv addendum.csv]
Writes: src/generated/messierSizes.ts
"""
import csv, hashlib, io, json, re, sys
from pathlib import Path
from urllib.request import urlopen

COMMIT = 'be3cd6c5498806a2fbb2f7e0452ef802dbb02be0'
BASE = f'https://raw.githubusercontent.com/mattiaverga/OpenNGC/{COMMIT}/database_files/'
CHECKSUMS = {'NGC.csv': '54abea0b57b0a103831bfc7a8e3a99a23acfbf4bb581fcf3d8af539cbb826c84',
             'addendum.csv': 'c93f983dda6780b76b7b2e9271a856a892627710148a982ee98101a54c642fdd'}
ROOT = Path(__file__).resolve().parents[1]


def light_years(text):
    """'6,500 light-years' -> 6500; '2.5 million light-years' -> 2.5e6; unknown -> None."""
    match = re.search(r'([\d.,]+)\s*(million|billion)?\s*light', text or '')
    if not match:
        return None
    value = float(match[1].replace(',', ''))
    return value * {'million': 1e6, 'billion': 1e9}.get(match[2], 1)


def main():
    records, by_name = {}, {}
    for index, (filename, checksum) in enumerate(CHECKSUMS.items(), 1):
        raw = Path(sys.argv[index]).read_bytes() if len(sys.argv) > index else urlopen(BASE + filename, timeout=60).read()
        if hashlib.sha256(raw).hexdigest() != checksum:
            raise SystemExit(f'Checksum mismatch: {filename}')
        for row in csv.DictReader(io.StringIO(raw.decode()), delimiter=';'):
            by_name[row['Name']] = row
            if row['M'] and row['Type'] != 'Dup':
                records[int(row['M'])] = row
    records[102] = by_name['NGC5866']
    assert set(records) == set(range(1, 111))
    distances = json.loads((ROOT / 'data/messier-distances.json').read_text())['distances']
    out = {}
    for number in range(1, 111):
        row = records[number]
        major = float(row['MajAx']) if row['MajAx'] else None
        minor = float(row['MinAx']) if row['MinAx'] else None
        out[f'm{number}'] = {'major': major, 'minor': minor, 'distanceLy': light_years(distances.get(str(number), {}).get('value'))}
    ts = ('// Generated by scripts/generate_messier_sizes.py — do not edit.\n'
          f'// Apparent sizes (arcmin) from OpenNGC by Mattia Verga, CC BY-SA 4.0, commit {COMMIT}.\n'
          '// distanceLy parsed from the NASA/Hubble distance snapshot in data/messier-distances.json.\n'
          'export type MessierSize = {major: number | null; minor: number | null; distanceLy: number | null};\n'
          f'export const messierSizes: Record<string, MessierSize> = {json.dumps(out, separators=(",", ":"))};\n')
    (ROOT / 'src/generated/messierSizes.ts').write_text(ts)
    print('sizes', sum(v['major'] is not None for v in out.values()), 'of 110; distances', sum(v['distanceLy'] is not None for v in out.values()))


if __name__ == '__main__':
    main()
