"""F-049/F-050: colour and identification extras for the bright star subset (HYG v4.1, CC BY-SA 4.0).

Uses the same pinned HYG file and the same selection as scripts/generate_bright_stars.py
(V <= 6.5 plus the two fainter constellation endpoints), in the same order, so index i
here belongs to brightStars[i]. Writes:
  src/generated/starColors.ts   B–V colour index ×100 per star (null when HYG has none)
  src/generated/starDetails.ts  designation (Bayer/Flamsteed), HD number, distance in
                                light-years, spectral type and constellation per star
The details file is loaded only when a star is tapped.

Run: python3 scripts/generate_star_extras.py [local hygdata_v41.csv]
"""
import csv, hashlib, io, json, re, sys
from pathlib import Path
from urllib.request import urlopen

HYG_COMMIT = '3bf37f4b2d5460e1278286320d1d62fab9b493c1'
SOURCE = f'https://raw.githubusercontent.com/astronexus/HYG-Database/{HYG_COMMIT}/hyg/CURRENT/hygdata_v41.csv'
SHA256 = 'd9f69fd86bbf90a4e4d52b4c5c53eacfa6dfc0bfdef85bfd94f095e0bebe4ebd'
ROOT = Path(__file__).resolve().parents[1]
REQUIRED = {30665, 33165}
GREEK = dict(Alp='α', Bet='β', Gam='γ', Del='δ', Eps='ε', Zet='ζ', Eta='η', The='θ', Iot='ι', Kap='κ', Lam='λ', Mu='μ', Nu='ν', Xi='ξ',
             Omi='ο', Pi='π', Rho='ρ', Sig='σ', Tau='τ', Ups='υ', Phi='φ', Chi='χ', Psi='ψ', Ome='ω')


def designation(bf):
    """'43Bet And' -> 'β And'; '33    Psc' -> '33 Psc'; 'Alp1Cen' -> 'α¹ Cen'."""
    match = re.match(r'^\s*(\d+)?\s*([A-Z][a-z]{1,2})?(\d)?\s*([A-Z][A-Za-z]{2})\s*$', bf or '')
    if not match:
        return None
    flamsteed, bayer, index, con = match.groups()
    if bayer in GREEK:
        return GREEK[bayer] + ('¹²³⁴⁵⁶⁷⁸⁹'[int(index) - 1] if index else '') + ' ' + con
    return f'{flamsteed} {con}' if flamsteed else None


def main():
    raw = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urlopen(SOURCE, timeout=300).read()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise SystemExit('HYG checksum mismatch')
    colors, details = [], []
    for row in csv.DictReader(io.StringIO(raw.decode('utf-8-sig'))):
        if row['id'] == '0' or not all(row[field] for field in ('ra', 'dec', 'mag')):
            continue
        hip = int(row['hip']) if row['hip'] else None
        if float(row['mag']) > 6.5 and hip not in REQUIRED:
            continue
        colors.append(round(float(row['ci']) * 100) if row['ci'] else None)
        dist = float(row['dist']) if row['dist'] else 0
        details.append([designation(row['bf']), int(row['hd']) if row['hd'] else None,
                        round(dist * 3.26156) if 0 < dist < 100000 else None, row['spect'] or None, row['con'] or None])
    if len(colors) != 8922:
        raise SystemExit(f'Unexpected subset size {len(colors)}')
    head = '// Generated by scripts/generate_star_extras.py from HYG v4.1 (CC BY-SA 4.0) — do not edit.\n// Same order as brightStars.ts.\n'
    (ROOT / 'src/generated/starColors.ts').write_text(head + '/** B–V colour index ×100, or null. */\nexport const starColorIndex: (number | null)[] = ' + json.dumps(colors, separators=(',', ':')) + ';\n')
    (ROOT / 'src/generated/starDetails.ts').write_text(head + '/** [designation, HD, distance in light-years, spectral type, constellation] */\nexport type StarDetail = [designation: string | null, hd: number | null, distanceLy: number | null, spectralType: string | null, constellation: string | null];\nexport const starDetails: StarDetail[] = ' + json.dumps(details, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(len(colors), 'stars;', sum(c is not None for c in colors), 'with colour;', sum(d[0] is not None for d in details), 'with designation')


if __name__ == '__main__':
    main()
