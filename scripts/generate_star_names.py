"""F-026: named bright stars as selectable objects.

Source: HYG v4.1 at the same pinned commit as the star field (CC BY-SA 4.0,
https://github.com/astronexus/HYG-Database). Proper names in HYG follow the
IAU Working Group on Star Names. Only stars that are already in the app's
8,922-star subset and are brighter than MAG_LIMIT are written.

Run: python3 scripts/generate_star_names.py -> src/generated/starNames.ts"""
import csv, io, json, re, urllib.request
from pathlib import Path

HYG = 'https://raw.githubusercontent.com/astronexus/HYG-Database/3bf37f4b2d5460e1278286320d1d62fab9b493c1/hyg/CURRENT/hygdata_v41.csv'
MAG_LIMIT = 2.6
ROOT = Path(__file__).resolve().parent.parent

def subset_hips():
    src = (ROOT / 'src/generated/brightStars.ts').read_text()
    i = src.index('brightStars: BrightStar[] = ') + len('brightStars: BrightStar[] = ')
    return {s[6] for s in json.loads(src[i:src.index('];', i) + 1]) if s[6]}

def main():
    hips = subset_hips()
    rows = []
    with urllib.request.urlopen(HYG, timeout=300) as response:
        for row in csv.DictReader(io.TextIOWrapper(response, encoding='utf-8')):
            if not row['proper'] or not row['hip'] or int(row['hip']) not in hips: continue
            mag = float(row['mag'])
            if mag > MAG_LIMIT: continue
            dist_pc = float(row['dist']) if row['dist'] else 0
            ly = round(dist_pc * 3.26156) if 0 < dist_pc < 100000 else None
            rows.append({'hip': int(row['hip']), 'name': row['proper'], 'mag': round(mag, 2), 'ra': round(float(row['ra']), 6),
                         'dec': round(float(row['dec']), 6), 'con': row['con'], 'ly': ly, 'spect': re.sub(r'\s+', ' ', row['spect'] or '')[:12]})
    rows.sort(key=lambda r: r['mag'])
    ts = ('// Generated by scripts/generate_star_names.py from HYG v4.1 (CC BY-SA 4.0) — do not edit.\n'
          '// Names follow the IAU WGSN list as carried in HYG. Distances are HYG estimates in light-years.\n'
          'export type StarName = {hip: number; name: string; mag: number; ra: number; dec: number; con: string; ly: number | null; spect: string};\n'
          f'export const starNames: StarName[] = {json.dumps(rows, ensure_ascii=False, separators=(",", ":"))};\n')
    (ROOT / 'src/generated/starNames.ts').write_text(ts, encoding='utf-8')
    print(len(rows), 'named stars')

if __name__ == '__main__':
    main()
